import pandas as pd
import numpy as np
import joblib

from sklearn.model_selection import train_test_split
from sklearn.metrics import mean_squared_error, mean_absolute_error, r2_score
from sklearn.preprocessing import LabelEncoder

from sklearn.ensemble import RandomForestRegressor, AdaBoostRegressor
from sklearn.tree import DecisionTreeRegressor
from xgboost import XGBRegressor
from catboost import CatBoostRegressor

df = pd.read_csv("/content/Fish.csv")
df

df.info()

from sklearn.preprocessing import MinMaxScaler

scaler = MinMaxScaler()
columns_to_scale = df.select_dtypes(include=['int64', 'float64']).columns
df[columns_to_scale] = scaler.fit_transform(df[columns_to_scale])
df

df['Species']
from sklearn.preprocessing import LabelEncoder
le = LabelEncoder()
df['Species'] = le.fit_transform(df['Species'])

df.columns

x = df[[ 'Weight', 'Length1', 'Length2', 'Length3', 'Height',
       'Width']]

y = df['Species']

x_train,x_test,y_train,y_test = train_test_split(x,y,test_size=0.20)

# Model

models = {
    "Decision Tree": DecisionTreeRegressor(),
    "Random Forest": RandomForestRegressor(),
    "AdaBoost": AdaBoostRegressor(),
    "XGBoost": XGBRegressor(use_label_encoder=False, eval_metric='logloss'),
    "CatBoost": CatBoostRegressor(verbose=0)  # suppress training output
}

# === Step 5: Train, Evaluate & Track Best Model ===
best_model = None
best_score = float('-inf')
best_name = ""

print("\n📊 Model Performance:\n")
for name, model in models.items():
    model.fit(x_train, y_train)
    preds = model.predict(x_test)

    mse = mean_squared_error(y_test, preds)
    mae = mean_absolute_error(y_test, preds)
    r2 = r2_score(y_test, preds)

    print(f"{name}: MSE={mse:.2f}, MAE={mae:.2f}, R²={r2:.4f}")

    # Use R² as the score to select best model
    if r2 > best_score:
        best_score = r2
        best_model = model
        best_name = name

# Save best model
import joblib
joblib.dump(best_model, f"{best_name}_best_model.pkl")
print(f"\n✅ Best model: '{best_name}' saved as '{best_name}_best_model.pkl' with R²: {best_score:.4f}")

